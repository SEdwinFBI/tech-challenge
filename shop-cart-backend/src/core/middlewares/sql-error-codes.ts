export function codigoDeNegocio(numero: number, mensaje = ''): string {
  if (numero === 50060) {
    if (/rechazado/i.test(mensaje)) return 'PAYMENT_REJECTED';
    if (/municipio/i.test(mensaje)) return 'MUNICIPALITY_NOT_FOUND';
    return 'DISCOUNT_TYPE_INVALID';
  }
  if (numero === 50082 && /positiva/i.test(mensaje)) return 'RETURN_QUANTITY_INVALID';
  return CODIGOS[numero] ?? `SQL_${numero}`;
}
